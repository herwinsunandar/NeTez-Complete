package com.herwin.netez.ui.viewmodels

import android.app.Application
import android.content.Intent
import androidx.lifecycle.AndroidViewModel
import androidx.lifecycle.viewModelScope
import com.herwin.netez.device.DeviceSecurityAuditEngine
import com.herwin.netez.device.DeviceSecurityAuditResult
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.StateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.launch

data class DeviceSecurityUiState(
    val auditResult: DeviceSecurityAuditResult? = null,
    val isScanning: Boolean = false,
    val error: String? = null
)

class DeviceSecurityViewModel(application: Application) : AndroidViewModel(application) {

    private val _uiState = MutableStateFlow(DeviceSecurityUiState())
    val uiState: StateFlow<DeviceSecurityUiState> = _uiState.asStateFlow()

    fun startScan() {
        viewModelScope.launch {
            _uiState.value = _uiState.value.copy(isScanning = true, error = null)
            try {
                val result = DeviceSecurityAuditEngine.runAudit(getApplication())
                _uiState.value = _uiState.value.copy(auditResult = result, isScanning = false)
            } catch (e: Exception) {
                _uiState.value = _uiState.value.copy(isScanning = false, error = e.message)
            }
        }
    }

    fun shareReport() {
        val result = _uiState.value.auditResult ?: return
        val report = StringBuilder("Netez Device Security Audit\n\n")
        report.append("Device: ${result.manufacturer} ${result.model}\n")
        report.append("Android: ${result.androidVersion}\n")
        report.append("Security Patch: ${result.securityPatch ?: "Unknown"}\n\n")
        report.append("Security Score: ${result.securityScore}/100\n")
        report.append("Grade: ${result.grade}\n\n")
        report.append("Critical: ${result.criticalCount}\n")
        report.append("Warnings: ${result.warningCount}\n")
        report.append("Safe: ${result.safeCount}\n")
        report.append("Info: ${result.infoCount}\n")
        report.append("Unknown: ${result.unknownCount}\n\n")
        
        result.checks.forEach {
            report.append("${it.name}: ${it.status}\n")
        }
        
        report.append("\nGenerated by Netez")
        
        val intent = Intent(Intent.ACTION_SEND).apply {
            type = "text/plain"
            putExtra(Intent.EXTRA_SUBJECT, "Device Security Audit Report")
            putExtra(Intent.EXTRA_TEXT, report.toString())
        }
        getApplication<Application>().startActivity(Intent.createChooser(intent, "Share Report").apply {
            addFlags(Intent.FLAG_ACTIVITY_NEW_TASK)
        })
    }
}
